function RootShell({ children }: { children: ReactNode }) {
  return (
    // `dark` is applied at the document root — not just on the inner
    // MarketingPage/AppShell wrapper divs — because Radix UI portals
    // (Select, DropdownMenu, Popover, Tooltip, Dialog content) mount
    // directly under <body> by default. With `dark` scoped only to an
    // inner wrapper, that portaled content fell outside the dark scope
    // and rendered with the unused `:root` light-theme tokens instead
    // (a white popover with a violet highlight) regardless of which
    // page it opened from. The app has no light-mode toggle, so this
    // is safe to apply unconditionally.
    <html lang="en" className="dark">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const pathname = useRouterState({ select: (s) => s.location.pathname });

  useEffect(() => {
    const { data: sub } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
      else queryClient.clear();
    });
    return () => sub.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <a
          href="#main"
          className="focus:bg-card sr-only focus:not-sr-only focus:fixed focus:top-3 focus:left-3 focus:z-100 focus:rounded-lg focus:px-4 focus:py-2 focus:shadow-lift"
        >
          Skip to content
        </a>
        {/* Required: nested routes render here. Removing <Outlet /> breaks
            all child routes. The key + animate-route-in class give every
            navigation a quick, subtle fade/rise/blur-in (~220ms) instead of
            an instant hard cut; prefers-reduced-motion zeroes this out
            globally (see styles.css). */}
        <div key={pathname} className="animate-route-in">
          <Outlet />
        </div>
        <Toaster position="top-right" richColors />
      </AuthProvider>
    </QueryClientProvider>
  );
}
